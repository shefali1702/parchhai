P.boot(() => {
  const $ = s => document.querySelector(s), $$ = s => [...document.querySelectorAll(s)];
  const CALLS = ["Nani", "Nana", "Dadi", "Dada", "Biji", "Bauji", "Paati", "Thatha", "Amma", "Appa"];
  const GLYPH = { en: "Aa", hi: "अ", pa: "ੳ", ta: "அ" };
  const form = { role: 0, call: "", lang: "", photo: null };
  let step = 0;

  const fam = P.db.family();
  if (fam) { $("#f-you").value = fam.name || ""; $("#f-email").value = fam.email || ""; form.role = fam.role ?? 0; }

  /* chips + language cards */
  function renderChoices() {
    $("#f-role").innerHTML = P.t("st.roles").map((r, i) => `<button type="button" class="chip" aria-pressed="${i === form.role}" data-i="${i}">${r}</button>`).join("");
    $$("#f-role .chip").forEach(b => b.onclick = () => { form.role = +b.dataset.i; renderChoices(); });
    $("#f-call").innerHTML = CALLS.map(c => `<button type="button" class="chip" aria-pressed="${c === form.call}" data-c="${c}">${c}</button>`).join("");
    $$("#f-call .chip").forEach(b => b.onclick = () => { form.call = b.dataset.c; $("#f-call-custom").value = ""; renderChoices(); });
    $("#f-lang").innerHTML = P.LANGS.map(l => `<button type="button" class="lang-card" role="radio" aria-checked="${l === form.lang}" data-l="${l}" lang="${l}">
      <span class="glyph">${GLYPH[l]}</span><b>${P.LANG_NAMES[l]}</b></button>`).join("");
    $$("#f-lang .lang-card").forEach(b => b.onclick = () => { form.lang = b.dataset.l; P.ding(); renderChoices(); });
  }
  $("#f-call-custom").addEventListener("input", e => { if (e.target.value.trim()) { form.call = ""; renderChoices(); } });
  const callName = () => $("#f-call-custom").value.trim() || form.call || $("#f-name").value.trim().split(" ")[0] || "…";

  /* photo */
  const ring = $("#photo-ring");
  const paintPhoto = () => { ring.innerHTML = form.photo ? `<img src="${form.photo}" alt="">` : P.icon("camera"); };
  async function takePhoto(file) {
    if (!file?.type.startsWith("image/")) return;
    try { form.photo = await P.db.shrinkPhoto(file); paintPhoto(); } catch { /* unreadable image: keep the placeholder */ }
  }
  $("#f-photo").addEventListener("change", e => takePhoto(e.target.files[0]));
  const ph = $("#photo");
  ph.addEventListener("dragover", e => { e.preventDefault(); ph.classList.add("drag"); });
  ph.addEventListener("dragleave", () => ph.classList.remove("drag"));
  ph.addEventListener("drop", e => { e.preventDefault(); ph.classList.remove("drag"); takePhoto(e.dataTransfer.files[0]); });
  paintPhoto();

  /* returning visitors */
  $$("[data-tab]").forEach(b => b.onclick = () => {
    $$("[data-tab]").forEach(x => x.setAttribute("aria-selected", String(x === b)));
    $$("[data-pane]").forEach(p => p.hidden = p.dataset.pane !== b.dataset.tab);
    $("#actions").hidden = b.dataset.tab === "back";
    paintBack();
  });
  function paintBack() {
    const has = P.db.elders().length;
    $("#back-msg").textContent = has ? P.t("st.backFound", { name: fam?.name || "" }) : P.t("st.backNone");
    $("#back-actions").innerHTML = has
      ? `<a class="btn btn-primary" href="vault.html">${P.t("st.continue")} ${P.icon("arrow")}</a>`
      : `<button class="btn btn-ghost" id="sample">${P.t("st.sample")}</button>`;
    $("#sample")?.addEventListener("click", async () => { await P.db.seedSample(); location.href = "vault.html"; });
  }

  /* stepping */
  function paintScene() {
    const k = Math.min(step, 4);
    ["#scene-k", "#scene-t", "#scene-p"].forEach(s => $(s).classList.add("out"));
    setTimeout(() => {
      $("#scene-k").innerHTML = P.t(`st.k${k}`); $("#scene-t").innerHTML = P.t(`st.h${k}`); $("#scene-p").innerHTML = P.t(`st.p${k}`);
      ["#scene-k", "#scene-t", "#scene-p"].forEach(s => $(s).classList.remove("out"));
    }, 300);
    document.querySelector(".scene").style.setProperty("--rise", [4, 13, 22, 31, 40][k]);
  }
  function show(n) {
    step = n;
    $$(".step").forEach(s => s.classList.toggle("on", +s.dataset.step === n));
    $$(".steps i").forEach((b, i) => b.classList.toggle("on", i <= n));
    $("#prev").style.visibility = n === 0 || n === 4 ? "hidden" : "visible";
    $("#actions").hidden = n === 4 || (n === 0 && $('[data-tab="back"]').getAttribute("aria-selected") === "true");
    $("#next-l").textContent = P.t(n === 3 ? "st.create" : "c.next");
    if (n === 3) { $("#consent-a").textContent = P.t("st.consentA", { call: callName() }); $("#c1-l").textContent = P.t("st.c1", { call: callName() }); }
    paintScene();
    if (n > 0) document.querySelector(".panel").scrollIntoView({ behavior: "smooth", block: "start" });
  }

  function validate() {
    if (step === 0 && !$("#f-you").value.trim()) return "st.errYou";
    if (step === 1 && !$("#f-name").value.trim()) return "st.errName";
    if (step === 2 && !form.lang) return "st.errLang";
    if (step === 3 && !($("#c1").checked && $("#c2").checked)) return "st.errConsent";
  }
  $("#next").addEventListener("click", () => {
    const err = validate();
    if (err) return P.toast(P.t(err));
    if (step === 0) P.db.saveFamily({ name: $("#f-you").value.trim(), email: $("#f-email").value.trim(), role: form.role });
    if (step === 3) {
      const elder = P.db.saveElder({
        name: $("#f-name").value.trim(), callName: callName(), lang: form.lang, dialect: $("#f-dialect").value.trim(),
        birthYear: +$("#f-born").value || null, hometown: $("#f-town").value.trim(), photo: form.photo, consentAt: Date.now(),
      });
      P.db.setActive(elder.id);
      $("#done-avatar").innerHTML = P.avatar(elder, "xl");
      $("#done-t").textContent = P.t("st.doneT", { call: elder.callName });
      P.ding("bell");
    }
    show(step + 1);
  });
  $("#prev").addEventListener("click", () => show(Math.max(0, step - 1)));

  document.addEventListener("langchange", () => {
    renderChoices(); paintScene(); paintBack();
    $("#next-l").textContent = P.t(step === 3 ? "st.create" : "c.next");
    if (step === 3) { $("#consent-a").textContent = P.t("st.consentA", { call: callName() }); $("#c1-l").textContent = P.t("st.c1", { call: callName() }); }
    if (step === 4) $("#done-t").textContent = P.t("st.doneT", { call: P.db.active()?.callName || "" });
  });

  show(new URLSearchParams(location.search).has("add") && fam ? 1 : 0);
  renderChoices();
});
