  $("#aloud").onchange = e => { P.store.set("parchhai-aloud", e.target.checked ? "1" : "0"); if (!e.target.checked) P.voice.stop(); };

  /* ---------- live visualiser: gold voice above, its violet shadow below ---------- */
  const viz = $("#viz"), vx = viz.getContext("2d");
  let analyser = null, freq = null;
  function sizeViz() { const d = Math.min(devicePixelRatio || 1, 2), r = viz.getBoundingClientRect(); viz.width = r.width * d; viz.height = r.height * d; vx.setTransform(d, 0, 0, d, 0, 0); }
  sizeViz(); addEventListener("resize", sizeViz);
  function drawViz(now) {
    const W = viz.clientWidth, H = viz.clientHeight, N = Math.max(24, Math.floor(W / 11)), mid = H * .62, bw = W / N;
    vx.clearRect(0, 0, W, H);
    if (analyser) analyser.getByteFrequencyData(freq);
    for (let i = 0; i < N; i++) {
      let v;
      if (analyser && state === "recording") {
        const bin = Math.floor(Math.pow(i / N, 1.6) * freq.length * .7);
        v = Math.max(.04, freq[bin] / 255);
      } else {
        v = .05 + .05 * (1 + Math.sin(now / 900 + i * .35)) * (state === "paused" ? .3 : 1);
      }
      const h = v * mid * .92, x = i * bw + bw * .2, w = bw * .6;
      const g = vx.createLinearGradient(0, mid - h, 0, mid);
      g.addColorStop(0, "#FFE6C4"); g.addColorStop(1, state === "recording" ? "#FF8A5C" : "#FFB062");
      vx.fillStyle = g; vx.beginPath(); vx.roundRect ? vx.roundRect(x, mid - h, w, h, w / 2) : vx.rect(x, mid - h, w, h); vx.fill();
      vx.fillStyle = "rgba(142, 107, 208, .28)";
      vx.beginPath(); vx.roundRect ? vx.roundRect(x, mid + 4, w, h * .42, w / 2) : vx.rect(x, mid + 4, w, h * .42); vx.fill();
    }
    vx.fillStyle = "rgba(246, 238, 227, .14)"; vx.fillRect(0, mid + 1, W, 1);
    requestAnimationFrame(drawViz);
  }
  requestAnimationFrame(drawViz);

  /* ---------- recording ---------- */
  let state = "idle", stream, mr, chunks = [], blob = null, mime = "", tStart = 0, elapsed = 0, tick, actx;
  let sr = null, finalText = "", player = null;
  const SR = window.SpeechRecognition || window.webkitSpeechRecognition;

  function setState(s, msg) {
    state = s;
    const studio = $("#studio");
    studio.classList.toggle("recording", s === "recording" || s === "paused");
    studio.classList.toggle("paused", s === "paused");
    $("#pause").hidden = !(s === "recording" || s === "paused");
    $("#pause").textContent = P.t(s === "paused" ? "rc.resume" : "rc.pause");
    $("#review").hidden = s !== "review";
    const st = $("#state");
    st.classList.toggle("err", !!msg);
    st.textContent = msg || P.t({ idle: "rc.ready", recording: "rc.recording", paused: "rc.paused", review: "rc.review" }[s], { call: elder.callName || elder.name });
    if (s === "idle") { $("#timer").textContent = "0:00"; $("#live").textContent = ""; }
  }

  function startSR() {
    if (!SR) return;
    try {
      sr = new SR(); sr.lang = P.BCP[elder.lang]; sr.continuous = true; sr.interimResults = true;
      sr.onresult = e => {
        let interim = "";
        for (let i = e.resultIndex; i < e.results.length; i++) {
          const r = e.results[i];
          r.isFinal ? (finalText += r[0].transcript.trim() + " ") : (interim += r[0].transcript);
        }
        $("#live").textContent = (finalText + interim).trim().slice(-160);
      };
      sr.onend = () => { if (state === "recording") { try { sr.start(); } catch {} } };
      sr.onerror = () => {};
      sr.start();
    } catch { sr = null; }
  }
  const stopSR = () => { try { sr?.stop(); } catch {} };

  async function start() {
    if (!navigator.mediaDevices?.getUserMedia || !window.MediaRecorder) return setState("idle", P.t("rc.noRec"));
    P.voice.stop(); document.body.classList.remove("speaking"); P.player.stopAll();
    try {
      stream = await navigator.mediaDevices.getUserMedia({ audio: { echoCancellation: true, noiseSuppression: true, autoGainControl: true } });
    } catch { return setState("idle", P.t("rc.noMic")); }
    mime = ["audio/webm;codecs=opus", "audio/mp4", "audio/webm", "audio/ogg"].find(m => MediaRecorder.isTypeSupported?.(m)) || "";
    mr = new MediaRecorder(stream, mime ? { mimeType: mime } : undefined);
    chunks = []; finalText = ""; elapsed = 0;
    mr.ondataavailable = e => e.data.size && chunks.push(e.data);
    mr.onstop = review;
    actx = new (window.AudioContext || window.webkitAudioContext)();
    analyser = actx.createAnalyser(); analyser.fftSize = 512; analyser.smoothingTimeConstant = .78;
    freq = new Uint8Array(analyser.frequencyBinCount);
    actx.createMediaStreamSource(stream).connect(analyser);
    mr.start(250); tStart = performance.now();
    tick = setInterval(() => { $("#timer").textContent = P.fmtTime((elapsed + (state === "recording" ? performance.now() - tStart : 0)) / 1000); }, 250);
    setState("recording"); startSR();
    if (SR) $("#live").textContent = P.t("rc.listening");
  }
  function stop() {
    if (state === "recording") elapsed += performance.now() - tStart;
    clearInterval(tick); stopSR();
    try { mr.state !== "inactive" && mr.stop(); } catch {}
    stream?.getTracks().forEach(t => t.stop());
    actx?.close?.(); analyser = null;
  }
  function pauseResume() {
    if (state === "recording") { mr.pause(); elapsed += performance.now() - tStart; stopSR(); setState("paused"); }
    else if (state === "paused") { mr.resume(); tStart = performance.now(); setState("recording"); startSR(); }
  }
  async function review() {
    blob = new Blob(chunks, { type: mime || chunks[0]?.type || "audio/webm" });
    setState("review");
    $("#live").textContent = "";
    $("#rv-text").value = finalText.trim();
    $("#rv-text").lang = elder.lang;
    player?.destroy();
    player = P.player.mount({ wave: $("#rv-wave"), btn: $("#rv-play"), time: $("#rv-time"), blob, duration: elapsed / 1000, peaks: await P.player.peaks(blob, 72) });
  }

  $("#rec").onclick = () => { interacted = true; state === "recording" || state === "paused" ? stop() : start(); };
  $("#pause").onclick = pauseResume;
  $("#retake").onclick = () => { player?.destroy(); blob = null; setState("idle"); };
  $("#save").onclick = async () => {
    if (!blob) return;
    const cur = q();
    await P.db.saveStory({
      id: P.uid(), elderId: elder.id, questionId: cur.id, theme: cur.theme, lang: elder.lang,
      audio: blob, mime: blob.type, duration: Math.round(elapsed / 1000), transcript: $("#rv-text").value.trim(),
      translation: "", listens: 0, createdAt: Date.now(),
    });
    answered.add(cur.id);
    player?.destroy(); blob = null;
    const li = document.createElement("li");
    li.innerHTML = `<span class="ok">${P.icon("check")}</span><span class="t" lang="${elder.lang}">${P.esc(cur.text[elder.lang])}</span><span class="faint small">${P.fmtTime(elapsed / 1000)}</span>`;
    $("#saved").prepend(li); $("#session").hidden = false;
    P.toast(P.t("rc.saved", { call: elder.callName || elder.name })); P.ding("bell");
    setState("idle"); go(1);
  };

